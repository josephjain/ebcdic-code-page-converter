/**
 * Internal registry mapping a canonical code page name to its forward
 * (ASCII->EBCDIC) table. The reverse table is computed lazily because not every
 * consumer needs both directions; the 256-byte cost is trivial, but building it
 * on demand keeps the module body free of duplicated data that could drift.
 */
const forwardTables = {
  '037': CP037,
  '500': CP500,
  '1047': CP1047,
};

/**
 * Build the inverse (EBCDIC->ASCII) table for a given forward table. If two
 * EBCDIC bytes map to the same ASCII byte (which does happen for a handful of
 * control-character slots in some code pages), the lowest EBCDIC index wins.
 * We document this as deterministic rather than trying to be clever about
 * disambiguation; there is no correct answer for a non-injective mapping.
 */
function buildReverse(forward) {
  const rev = new Uint8Array(256);
  // Default every slot to 0x00 so unmapped EBCDIC bytes degrade to NUL rather
  // than throwing; this mirrors how mainframe tooling typically handles
  // untranslatable bytes in streaming contexts.
  rev.fill(0x00);
  for (let i = 0; i < 256; i++) {
    const ebcdicByte = forward[i];
    if (rev[ebcdicByte] === 0x00 && i !== 0x00) {
      rev[ebcdicByte] = i;
    }
  }
  // Ensure 0x00 round-trips.
  rev[0x00] = 0x00;
  return rev;
}

const reverseTables = {};

/**
 * Resolve a code page name to its canonical string key. We accept numbers and
 * strings so callers can pass `1047` or `'1047'` interchangeably; the brief
 * lists the code pages as bare integers, so being strict about string type
 * would be pedantic without benefit. The name is zero-padded to three digits
 * because the canonical IBM naming uses that form.
 */
function resolveCodePage(codePage) {
  const key = String(codePage).padStart(3, '0');
  if (!forwardTables[key]) {
    throw new RangeError(
      `Unsupported code page: ${codePage}. Supported: 037, 500, 1047.`
    );
  }
  return key;
}

/**
 * Get the forward (ASCII->EBCDIC) table for a code page.
 */
export function getForwardTable(codePage) {
  return forwardTables[resolveCodePage(codePage)];
}

/**
 * Get the reverse (EBCDIC->ASCII) table for a code page.
 */
export function getReverseTable(codePage) {
  const key = resolveCodePage(codePage);
  if (!reverseTables[key]) {
    reverseTables[key] = buildReverse(forwardTables[key]);
  }
  return reverseTables[key];
}

/**
 * Convert a Buffer or Uint8Array of ASCII bytes to EBCDIC bytes.
 *
 * @param {Uint8Array|Buffer} input - ASCII (ISO-8859-1) bytes. Each byte's
 *   unsigned value is used as an index into the code page table.
 * @param {string|number} codePage - One of 037, 500, 1047.
 * @returns {Uint8Array} A new Uint8Array of the same length containing EBCDIC
 *   bytes. The input is never mutated; callers that already hold a Uint8Array
 *   can safely keep using it.
 */
export function asciiToEbcdic(input, codePage) {
  if (!(input instanceof Uint8Array)) {
    throw new TypeError('input must be a Uint8Array or Buffer');
  }
  const table = getForwardTable(codePage);
  const out = new Uint8Array(input.length);
  for (let i = 0; i < input.length; i++) {
    out[i] = table[input[i]];
  }
  return out;
}

/**
 * Convert a Buffer or Uint8Array of EBCDIC bytes to ASCII bytes.
 *
 * @param {Uint8Array|Buffer} input - EBCDIC bytes.
 * @param {string|number} codePage - One of 037, 500, 1047.
 * @returns {Uint8Array} A new Uint8Array of the same length containing ASCII
 *   bytes. EBCDIC bytes with no defined ASCII equivalent become 0x00 (NUL).
 */
export function ebcdicToAscii(input, codePage) {
  if (!(input instanceof Uint8Array)) {
    throw new TypeError('input must be a Uint8Array or Buffer');
  }
  const table = getReverseTable(codePage);
  const out = new Uint8Array(input.length);
  for (let i = 0; i < input.length; i++) {
    out[i] = table[input[i]];
  }
  return out;
}

/**
 * List the supported code page identifiers as strings.
 */
export function supportedCodePages() {
  return Object.keys(forwardTables);
}
