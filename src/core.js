/**
 * EBCDIC code page tables and conversion logic.
 *
 * Design decision: we precompute bidirectional lookup tables (Uint8Array of
 * 256 entries) at module load. The tables are small and flat, so a linear scan
 * is unnecessary; direct indexing is O(1) and branch-free, which matters for the
 * bulk-conversion path. We deliberately expose `asciiToEbcdic` and `ebcdicToAscii`
 * as the canonical API rather than a generic `convert(buf, from, to)` because the
 * underlying tables are always ASCII<->EBCDIC pairs; a generic converter would
 * imply support for EBCDIC-to-EBCDIC transcoding, which we do not provide.
 */

